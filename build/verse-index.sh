#!/bin/sh
# verse-index.sh -- index every project you OWN into one queryable set.
#
# VIKIVERSE_V1 2.7. The measured case for it: an agent proposed rebuilding
# SQLCipher-for-wasm that already existed one directory over, with its build
# recipe sitting in a CI file in the same tree. Coverage dominates ranking --
# that document was not ranked badly, it was not in the corpus.
#
# OWNERSHIP DECIDES DEPTH, which is Warren's rule and it is the right one:
#
#   OWN    origin matches $VIKI_VERSE_OWNER, no upstream remote     -> INDEX ALL
#   LOCAL  no remote at all -- yours by default                      -> INDEX ALL
#   FORK   has an `upstream` remote -- your name on someone else's   -> DIFF ONLY
#          project. This is the case a remote-name check gets wrong:
#          wmacevoy/sqlcipher-libressl looks OWNED and is 31,057 chunks of
#          upstream SQLCipher. The `upstream` remote is the honest marker.
#   CLONE  origin is someone else's                                  -> SKIP,
#          unless you are ahead of it, then DIFF ONLY.
#
# DIFF ONLY means: index just the files you changed relative to the upstream
# merge-base. Reading a clone of flutter/flutter into your memory is 100k files
# of someone else's decisions; reading the three files you changed is YOUR
# decision about their code, which is the part worth remembering.
#
# Each project keeps its own .viki/cache.db (D-10: derived, disposable, per
# repo) and the registry just points at them. Nothing is centralised, so a
# project can be re-indexed, moved or dropped without touching the others.
#
# Usage:
#   sh build/verse-index.sh [projects-dir]        # default ~/projects
#     VIKI_VERSE=<file>        registry to write   (default ~/.viki/verse.tsv)
#     VIKI_VERSE_OWNER=<name>  ownership match     (default from git config)
#     VIKI_VERSE_MAX_FILES=N   refuse a project bigger than this (default 4000)
set -e

DIR="${1:-$HOME/projects}"
ROOT=$(cd "$(dirname "$0")/.." && pwd)
V="${VIKI_BIN:-$ROOT/build/dist/viki}"
REG="${VIKI_VERSE:-$HOME/.viki/verse.tsv}"
OWNER="${VIKI_VERSE_OWNER:-$(git config --get user.name 2>/dev/null | tr 'A-Z ' 'a-z-')}"
[ -n "$OWNER" ] || OWNER="$(id -un)"
[ -x "$V" ] || { echo "no viki at $V"; exit 2; }
[ -d "$DIR" ] || { echo "no such directory: $DIR"; exit 2; }
mkdir -p "$(dirname "$REG")"

# A shared ignore set, applied to any project without its own .vikiignore.
# It exists because the first survey found 14,186 "prose" files in one repo
# of which 14,144 were processed Shakespeare -- a course dataset, not a
# decision. Data dumps drown the thing you are actually looking for.
# Bumped whenever DEFAULT_IGNORE changes. A file carrying an OLDER marker was
# generated by this script and never touched, so it is safe to replace -- which
# is what fixes the real bug: run 1 wrote an ignore list without `env`, run 2
# added it, and every project from run 1 kept indexing its virtualenv because
# the script refused to overwrite its own stale output. Delete the marker line
# to make a file yours; it will never be replaced after that.
IGNORE_VERSION=2
DEFAULT_IGNORE='# verse-index.sh v2 -- delete this line to keep your own edits
# Dependency trees. Named several ways in the wild: one project here keeps a
# per-platform virtualenv at core/env/Darwin-arm64, which is why `env` and
# `site-packages` are both listed and why the guard below exists anyway.
node_modules
.venv
venv
env
virtualenv
site-packages
__pycache__
.tox
.gradle
Pods
target
dist
build
out
vendor
third_party
.viki
*.o
*.a
*.so
*.pyc
*.class
*.wasm
*.min.js
*.map
*.lock
*.dSYM
*.plist
.vikiignore
# data, not decisions. The first survey found 14,186 "prose" files in one repo
# of which 14,144 were processed Shakespeare -- a course dataset.
data/processed
data/raw
datasets
*.csv
*.tsv
*.parquet
*.ipynb_checkpoints
'

printf '# viki verse registry -- written %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" > "$REG.tmp"
printf '# label\tcache.db     (regenerate with build/verse-index.sh)\n' >> "$REG.tmp"

nOwn=0; nClone=0; nSkip=0; nFail=0; nBig=0
for d in "$DIR"/*/; do
  name=$(basename "$d")
  [ -d "$d" ] || continue

  remote=$(git -C "$d" config --get remote.origin.url 2>/dev/null || true)
  upstream=$(git -C "$d" config --get remote.upstream.url 2>/dev/null || true)
  kind=LOCAL
  if [ -n "$upstream" ]; then
    kind=FORK
  elif [ -n "$remote" ]; then
    case "$(printf '%s' "$remote" | tr 'A-Z' 'a-z')" in
      *"$OWNER"*) kind=OWN ;;
      *)          kind=CLONE ;;
    esac
  fi

  base=""
  case "$kind" in
    FORK)
      # Files changed since the merge-base with upstream's default branch.
      ub=$(git -C "$d" rev-parse --verify -q upstream/main 2>/dev/null \
           || git -C "$d" rev-parse --verify -q upstream/master 2>/dev/null || true)
      [ -n "$ub" ] && base=$(git -C "$d" merge-base "$ub" HEAD 2>/dev/null || true)
      if [ -z "$base" ]; then
        # No upstream refs fetched, so the diff cannot be computed. Skipping is
        # the conservative call: indexing the whole fork would drown the verse,
        # and that is the failure this branch exists to prevent.
        printf '  %-8s %s  (no upstream ref fetched -- skipped)\n' SKIP "$name"
        nSkip=$((nSkip+1)); continue
      fi
      nClone=$((nClone+1))
      ;;
    CLONE)
      ahead=$(git -C "$d" rev-list --count '@{upstream}..HEAD' 2>/dev/null || echo 0)
      if [ "${ahead:-0}" -eq 0 ]; then nSkip=$((nSkip+1)); continue; fi
      base=$(git -C "$d" rev-parse --verify -q '@{upstream}' 2>/dev/null || true)
      nClone=$((nClone+1))
      ;;
    *)
      nOwn=$((nOwn+1))
      ;;
  esac

  # Write ours if absent, or refresh a stale one WE wrote. A file whose first
  # line is not our marker belongs to the user and is never touched.
  if [ ! -f "$d/.vikiignore" ]; then
    printf '%s' "$DEFAULT_IGNORE" > "$d/.vikiignore"
  else
    first=$(head -1 "$d/.vikiignore")
    case "$first" in
      "# verse-index.sh v$IGNORE_VERSION"*) : ;;
      "# verse-index.sh v"*|"# written by verse-index.sh"*)
        printf '%s' "$DEFAULT_IGNORE" > "$d/.vikiignore" ;;
      *) : ;;
    esac
  fi

  if [ -n "$base" ]; then
    # A fork's own contribution, expressed as an ignore file: everything
    # EXCEPT the changed paths. viki has no include-list, and adding one for
    # this would be a schema-shaped answer to a scripting problem -- the
    # changed set is small, so listing what to keep is cheap.
    changed=$(git -C "$d" diff --name-only "$base" HEAD 2>/dev/null | head -400)
    if [ -z "$changed" ]; then
      printf '  %-8s %s  (identical to upstream -- skipped)\n' SKIP "$name"
      nSkip=$((nSkip+1)); nClone=$((nClone-1)); continue
    fi
    ( cd "$d" && rm -rf .viki/fork-view && mkdir -p .viki/fork-view
      printf '%s\n' "$changed" | while read -r f; do
        [ -f "$f" ] || continue
        mkdir -p ".viki/fork-view/$(dirname "$f")"
        cp "$f" ".viki/fork-view/$f" 2>/dev/null || true
      done )
  fi

  # SIZE GUARD, and it is here because of a real stall rather than a worry.
  # `darter` is 6.1GB / 28,858 files -- a per-platform virtualenv the default
  # ignore did not name -- and the run sat on it for over nine minutes with
  # zero chunks written and no output. Silence indistinguishable from work is
  # exactly the failure VIKIVERSE_V1 2.9 forbids, so: count first, and refuse
  # loudly with the fix in the message. A project that WANTS to be big says so
  # by raising the cap.
  MAXF="${VIKI_VERSE_MAX_FILES:-4000}"
  nCand=$(find "$d" -type f \
            -not -path '*/.git/*' -not -path '*/node_modules/*' \
            -not -path '*/.venv/*' -not -path '*/venv/*' -not -path '*/env/*' \
            -not -path '*/__pycache__/*' -not -path '*/.viki/*' \
            -not -path '*/vendor/*' -not -path '*/build/*' -not -path '*/dist/*' \
            2>/dev/null | head -$((MAXF + 1)) | wc -l | tr -d ' ')
  if [ "${nCand:-0}" -gt "$MAXF" ]; then
    printf '  %-8s %-32s >%s files -- add a .vikiignore, or raise VIKI_VERSE_MAX_FILES\n' \
           BIG "$name" "$MAXF"
    nBig=$((nBig+1)); continue
  fi

  printf '  %-8s %s' "$kind" "$name"
  target="."
  [ -n "$base" ] && target=".viki/fork-view"
  if ( cd "$d" && "$V" index "$target" >/dev/null 2>&1 ); then
    n=$(sqlite3 "$d/.viki/cache.db" "SELECT count(*) FROM viki_chunk;" 2>/dev/null || echo 0)
    printf '  %s chunks\n' "$n"
    if [ "${n:-0}" -gt 0 ]; then
      printf '%s\t%s\n' "$name" "$(cd "$d" && pwd)/.viki/cache.db" >> "$REG.tmp"
    fi
  else
    printf '  FAILED\n'; nFail=$((nFail+1))
  fi
done

mv "$REG.tmp" "$REG"
echo
echo "registry: $REG"
echo "  $nOwn owned in full, $nClone fork/clone DIFF ONLY, $nSkip skipped, $nBig too big, $nFail failed"
[ "$nBig" -gt 0 ] && echo "  the too-big ones are listed above; each needs a .vikiignore naming its dependency tree"
echo "  ask across it:  viki ask \"<query>\" --verse"
