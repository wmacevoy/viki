/* Decodes one UTF-8 codepoint, advancing *pz past it. Returns -1 for an
** invalid sequence, consuming exactly one byte -- the caller deletes it,
** which is what the reference does with the U+FFFD that Python's decoder
** would have produced in its place. Never reads past the NUL. */
static int utf8_next(const unsigned char **pz){
    const unsigned char *z = *pz;
    unsigned c0 = z[0], c1, c2, c3;
    int cp;

    if( c0 < 0x80 ){ *pz = z + 1; return (int)c0; }
    if( c0 >= 0xC2 && c0 <= 0xDF ){
        c1 = z[1];
        if( (c1 & 0xC0) == 0x80 ){
            *pz = z + 2;
            return (int)(((c0 & 0x1F) << 6) | (c1 & 0x3F));
        }
    }else if( (c0 & 0xF0) == 0xE0 ){
        c1 = z[1];
        if( (c1 & 0xC0) == 0x80 ){
            c2 = z[2];
            if( (c2 & 0xC0) == 0x80 ){
                cp = (int)(((c0 & 0x0F) << 12) | ((c1 & 0x3F) << 6) | (c2 & 0x3F));
                /* reject overlongs and the surrogate range: both are
                ** undecodable to Python, hence U+FFFD, hence deleted */
                if( cp >= 0x800 && (cp < 0xD800 || cp > 0xDFFF) ){ *pz = z + 3; return cp; }
            }
        }
    }else if( c0 >= 0xF0 && c0 <= 0xF4 ){
        c1 = z[1];
        if( (c1 & 0xC0) == 0x80 ){
            c2 = z[2];
            if( (c2 & 0xC0) == 0x80 ){
                c3 = z[3];
                if( (c3 & 0xC0) == 0x80 ){
                    cp = (int)(((c0 & 0x07) << 18) | ((c1 & 0x3F) << 12) |
                               ((c2 & 0x3F) << 6) | (c3 & 0x3F));
                    if( cp >= 0x10000 && cp <= 0x10FFFF ){ *pz = z + 4; return cp; }
                }
            }
        }
    }
    *pz = z + 1;
    return -1;
}

/* Encodes cp into z (no NUL), returns the byte count (1..4). */
static int utf8_put(char *z, int cp){
    if( cp < 0x80 ){
        z[0] = (char)cp;
        return 1;
    }
    if( cp < 0x800 ){
        z[0] = (char)(0xC0 | (cp >> 6));
        z[1] = (char)(0x80 | (cp & 0x3F));
        return 2;
    }
    if( cp < 0x10000 ){
        z[0] = (char)(0xE0 | (cp >> 12));
        z[1] = (char)(0x80 | ((cp >> 6) & 0x3F));
        z[2] = (char)(0x80 | (cp & 0x3F));
        return 3;
    }
    z[0] = (char)(0xF0 | (cp >> 18));
    z[1] = (char)(0x80 | ((cp >> 12) & 0x3F));
    z[2] = (char)(0x80 | ((cp >> 6) & 0x3F));
    z[3] = (char)(0x80 | (cp & 0x3F));
    return 4;
}

static int in_ranges(const unsigned int a[][2], int n, int cp){
    int lo = 0, hi = n - 1;
    while( lo <= hi ){
        int mid = (lo + hi) / 2;
        if( (unsigned)cp < a[mid][0] ) hi = mid - 1;
        else if( (unsigned)cp > a[mid][1] ) lo = mid + 1;
        else return 1;
    }
    return 0;
}

/* reference _is_control(): every C* category except \t \n \r. Cn
** (unassigned) is deliberately NOT included -- see tokenizer.h. */
static int cp_is_control(int cp){
    if( cp < 0x80 ){
        if( cp == '\t' || cp == '\n' || cp == '\r' ) return 0;
        return cp < 0x20 || cp == 0x7F;
    }
    return in_ranges(aCtlRange, nCtlRange, cp);
}

/* Where the reference actually breaks tokens. NOT simply _is_whitespace():
** that predicate covers ' ' \t \n \r and category Zs, but the split itself
** is whitespace_tokenize(), i.e. Python's str.split(), which ALSO breaks on
** U+2028 (Zl) and U+2029 (Zp). Every other codepoint str.split() breaks on
** is category Cc, and _clean_text has deleted those before the split ever
** runs, so Zl/Zp are the entire difference. Found by sweeping all 1,112,032
** codepoints through this file -- reading the reference had missed it. */
static int cp_is_space(int cp){
    if( cp < 0x80 ) return cp == ' ' || cp == '\t' || cp == '\n' || cp == '\r';
    return in_ranges(aSpaceRange, nSpaceRange, cp);
}

/* reference _is_punctuation(): the four ASCII ranges plus category P* */
static int cp_is_punct(int cp){
    if( cp < 0x80 ) return is_ascii_punct((unsigned char)cp);
    return in_ranges(aPunctRange, nPunctRange, cp);
}

static int cp_is_mark(int cp){
    if( cp < 0x300 ) return 0;
    return in_ranges(aMarkRange, nMarkRange, cp);
}

/* reference _is_chinese_char(): the CJK ideograph blocks ONLY -- kana and
** Hangul are deliberately absent from this list upstream, so they are not
** split per character. */
static int cp_is_cjk(int cp){
    return (cp >= 0x4E00  && cp <= 0x9FFF)  ||
           (cp >= 0x3400  && cp <= 0x4DBF)  ||
           (cp >= 0x20000 && cp <= 0x2A6DF) ||
           (cp >= 0x2A700 && cp <= 0x2B73F) ||
           (cp >= 0x2B740 && cp <= 0x2B81F) ||
           (cp >= 0x2B820 && cp <= 0x2CEAF) ||
           (cp >= 0xF900  && cp <= 0xFAFF)  ||
           (cp >= 0x2F800 && cp <= 0x2FA1F);
}

static int cp_lower(int cp){
    int lo, hi;
    if( cp < 0x80 ) return (cp >= 'A' && cp <= 'Z') ? cp + 32 : cp;
    lo = 0; hi = nLowerRun - 1;
    while( lo <= hi ){
        int mid = (lo + hi) / 2;
        if( cp < aLowerRun[mid][0] ) hi = mid - 1;
        else if( cp > aLowerRun[mid][1] ) lo = mid + 1;
        else{
            /* a run is (lo,hi,step,delta); codepoints off the step are not
            ** members of it -- that is how the alternating upper/lower
            ** layout of Latin Extended-A compresses at all */
            if( (cp - aLowerRun[mid][0]) % aLowerRun[mid][2] ) return cp;
            return cp + aLowerRun[mid][3];
        }
    }
    return cp;
}

/* Canonical decomposition with the Mn removed, i.e. reference
** _run_strip_accents on a single codepoint. Writes 1..3 codepoints to
** aOut and returns the count. */
static int cp_strip(int cp, int *aOut){
    int lo, hi;

    if( cp >= 0xAC00 && cp <= 0xD7A3 ){
        /* Hangul decomposes by formula, not by table (UAX #15) -- L and V
        ** and T are all jamo, none of them Mn, so all of them survive. */
        int i = cp - 0xAC00, t = i % 28;
        aOut[0] = 0x1100 + i / 588;
        aOut[1] = 0x1161 + (i % 588) / 28;
        if( t ){ aOut[2] = 0x11A7 + t; return 3; }
        return 2;
    }
    if( cp >= FOLD_LATIN_LO && cp <= FOLD_LATIN_HI ){
        int r = aFoldLatin[cp - FOLD_LATIN_LO];
        aOut[0] = r ? r : cp;
        return 1;
    }
    if( cp >= FOLD_GRCY_LO && cp <= FOLD_GRCY_HI ){
        int r = aFoldGrCy[cp - FOLD_GRCY_LO];
        aOut[0] = r ? r : cp;
        return 1;
    }
    if( cp >= FOLD_LATAD_LO && cp <= FOLD_LATAD_HI ){
        int r = aFoldLatAd[cp - FOLD_LATAD_LO];
        aOut[0] = r ? r : cp;
        return 1;
    }
    if( cp >= FOLD_KANA_LO && cp <= FOLD_KANA_HI ){
        int r = aFoldKana[cp - FOLD_KANA_LO];
        aOut[0] = r ? r : cp;
        return 1;
    }
    lo = 0; hi = nFoldOther - 1;
    while( lo <= hi ){
        int mid = (lo + hi) / 2;
        if( (unsigned)cp < aFoldOther[mid][0] ) hi = mid - 1;
        else if( (unsigned)cp > aFoldOther[mid][0] ) lo = mid + 1;
        else{
            /* row is {cp, r0, r1, r2} with unused replacements zeroed */
            int n = 0;
            while( n < 3 && aFoldOther[mid][n + 1] ){ aOut[n] = (int)aFoldOther[mid][n + 1]; n++; }
            return n;
        }
    }
    aOut[0] = cp;
    return 1;
}

/* lower -> strip accents -> lower again. The second lower() is not
** belt-and-braces: U+0130 LATIN CAPITAL LETTER I WITH DOT ABOVE has a
** TWO-codepoint lowercase, so it is absent from the 1:1 lowercase table
** and reaches cp_strip() still uppercase; its NFD base is ASCII 'I', and
** only the second pass turns that into the reference's 'i'. */
static int strip_and_lower(int cp, int *aOut){
    int n, i;
    n = cp_strip(cp_lower(cp), aOut);
    for( i = 0; i < n; i++ ) aOut[i] = cp_lower(aOut[i]);
    return n;
}

static int basic_tokenize_conformant(const char *zText, char basicToks[][MAX_TOKEN_LEN]){
    const unsigned char *p = (const unsigned char*)zText;
    int n = 0;      /* completed basic tokens */
    int len = 0;    /* bytes buffered into basicToks[n] so far */

    while( *p && n < MAX_BASIC_TOKENS ){
        int cp = utf8_next(&p);
        int aStrip[3], nStrip, i;

        /* _clean_text DELETES control characters, it does not break on
        ** them -- so "alpha<0x01>beta" is one word "alphabeta". */
        if( cp < 0 || cp == 0xFFFD || cp_is_control(cp) ) continue;

        if( cp_is_space(cp) ){
            if( len > 0 ){ basicToks[n][len] = '\0'; n++; len = 0; }
            continue;
        }

        /* A combining mark already present in the input is dropped by
        ** _run_strip_accents exactly like one NFD would have produced. */
        if( cp_is_mark(cp) ) continue;

        /* _tokenize_chinese_chars runs on the RAW text, before lowercasing,
        ** and pads each CJK codepoint with spaces -- so each one is its own
        ** basic token regardless of what surrounds it. */
        if( cp_is_cjk(cp) ){
            if( len > 0 ){ basicToks[n][len] = '\0'; n++; len = 0; }
            if( n >= MAX_BASIC_TOKENS ) break;
            len = utf8_put(basicToks[n], cp);
            basicToks[n][len] = '\0';
            n++;
            len = 0;
            continue;
        }

        nStrip = strip_and_lower(cp, aStrip);
        for( i = 0; i < nStrip && n < MAX_BASIC_TOKENS; i++ ){
            int c = aStrip[i];
            if( cp_is_punct(c) ){
                if( len > 0 ){ basicToks[n][len] = '\0'; n++; len = 0; }
                if( n >= MAX_BASIC_TOKENS ) break;
                len = utf8_put(basicToks[n], c);
                basicToks[n][len] = '\0';
                n++;
                len = 0;
                continue;
            }
            /* Refusing to buffer past MAX_TOKEN_LEN-5 is not a truncation
            ** that can change the answer: a word that reaches 508 bytes of
            ** UTF-8 is at least 127 characters, and wordpiece_one() maps
            ** anything over 100 characters to [UNK] regardless of what the
            ** rest of it said. */
            if( len <= MAX_TOKEN_LEN - 5 ) len += utf8_put(basicToks[n] + len, c);
        }
    }
    if( len > 0 && n < MAX_BASIC_TOKENS ){ basicToks[n][len] = '\0'; n++; }
    return n;
}
