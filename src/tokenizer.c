/* Greedy longest-match-first WordPiece on one basic token. Appends
** resulting subword ids to outIds, advancing *pOutN (bounded by maxLen).
** Falls back to [UNK] if no split covers the whole token. */
static void wordpiece_one(const viki_vocab *v, const char *word, int *outIds, int *pOutN, int maxLen){
    size_t len = strlen(word);
    size_t start = 0;
    int piecesStart = *pOutN;
    char buf[MAX_TOKEN_LEN + 3]; /* room for "##" prefix */

    if( len == 0 ) return;

#ifdef VIKI_TOKENIZER_CONFORMANT
    /* Reference WordpieceTokenizer.max_input_chars_per_word = 100: a word
    ** longer than that is [UNK] outright and is never pieced. The legacy
    ** path has no such rule -- it pieces up to 127 BYTES and then silently
    ** drops the remainder of the run (see basic_tokenize), which both
    ** diverges from the reference and wastes budget. */
    {
        size_t i, nChars = 0;
        for( i = 0; i < len; i++ ) if( ((unsigned char)word[i] & 0xC0) != 0x80 ) nChars++;
        if( nChars > 100 ){
            if( *pOutN < maxLen ) outIds[(*pOutN)++] = v->unkId;
            return;
        }
    }
#endif

    while( start < len && *pOutN < maxLen ){
        size_t end = len;
        int found = -1;
        while( end > start ){
            size_t plen = end - start;
            if( start == 0 ){
                if( plen > MAX_TOKEN_LEN - 1 ) { end--; continue; }
                memcpy(buf, word + start, plen);
                buf[plen] = '\0';
            }else{
                if( plen > MAX_TOKEN_LEN - 3 ) { end--; continue; }
                buf[0] = '#'; buf[1] = '#';
                memcpy(buf + 2, word + start, plen);
                buf[plen + 2] = '\0';
            }
            found = vocab_lookup(v, buf);
            if( found >= 0 ) break;
            end--;
#ifdef VIKI_TOKENIZER_CONFORMANT
            /* Reference WordPiece backs off one CHARACTER at a time. A cut
            ** inside a UTF-8 sequence could not match a vocab entry anyway
            ** (every entry is valid UTF-8), so this is an invariant made
            ** explicit rather than a behaviour change -- but leaving it
            ** implicit is how a later "optimisation" turns into a bug. */
            while( end > start && ((unsigned char)word[end] & 0xC0) == 0x80 ) end--;
#endif
        }
        if( found < 0 ){
            /* No valid split for this word at all: whole word -> [UNK],
            ** discard any pieces already emitted for it. */
            *pOutN = piecesStart;
            if( *pOutN < maxLen ) outIds[(*pOutN)++] = v->unkId;
            return;
        }
        outIds[(*pOutN)++] = found;
        start = end;
    }
}

int viki_tokenize(const viki_vocab *v, const char *zText, int *outIds, int maxLen){
    static char basicToks[MAX_BASIC_TOKENS][MAX_TOKEN_LEN];
#ifdef VIKI_TOKENIZER_CONFORMANT
    int nBasic = basic_tokenize_conformant(zText, basicToks);
#else
    int nBasic = basic_tokenize(zText, basicToks);
#endif
    int n = 0;
    int i;

    if( maxLen < 2 ) return 0;
    outIds[n++] = v->clsId;

    for( i = 0; i < nBasic && n < maxLen - 1; i++ ){
        wordpiece_one(v, basicToks[i], outIds, &n, maxLen - 1 /* leave room for [SEP] */);
    }

    outIds[n++] = v->sepId;
    return n;
}
